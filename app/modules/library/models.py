from sqlalchemy import BigInteger, Boolean, Column, Date, DateTime, ForeignKey, Integer, Numeric, String, Text
from sqlalchemy.sql import func
from core.database import Base

class OrgLibraryBook(Base):
    __tablename__ = 'org_library_books'
    id = Column(BigInteger, primary_key=True)
    organization_id = Column(Integer)
    title = Column(String(255))
    subtitle = Column(String(255))
    isbn_10 = Column(String(20))
    isbn_13 = Column(String(20))
    accession_no = Column(String(100))
    call_number = Column(String(100))
    edition = Column(String(100))
    language = Column(Integer)
    description = Column(Text)
    cover_image = Column(String(255))
    publication_year = Column(Integer)
    pages = Column(Integer)
    price = Column(Numeric(10, 2))
    category_id = Column(Integer)
    publisher_id = Column(Integer)
    status = Column(Integer)
    is_reference_only = Column(Boolean, default=False)
    is_active = Column(Boolean, default=True)
    created_by_id = Column(Integer)
    created_at = Column(DateTime, server_default=func.now())
    updated_at = Column(DateTime, server_default=func.now(), onupdate=func.now())

class OrgLibraryBookCopy(Base):
    __tablename__ = 'org_library_book_copies'
    id = Column(BigInteger, primary_key=True)
    organization_id = Column(Integer)
    book_id = Column(BigInteger, ForeignKey('org_library_books.id', ondelete='CASCADE'))
    barcode = Column(String(100), unique=True)
    copy_no = Column(Integer)
    branch_id = Column(Integer)
    shelf_id = Column(Integer)
    condition = Column(Integer)
    status = Column(Integer)
    purchase_date = Column(Date)
    purchase_price = Column(Numeric(10, 2))
    is_active = Column(Boolean, default=True)
    acquired_by_id = Column(Integer)
    created_at = Column(DateTime, server_default=func.now())
    updated_at = Column(DateTime, server_default=func.now(), onupdate=func.now())

class OrgLibraryMember(Base):
    __tablename__ = 'org_library_members'
    id = Column(BigInteger, primary_key=True)
    organization_id = Column(Integer)
    member_type = Column(Integer)
    student_id = Column(BigInteger, index=True)
    staff_id = Column(BigInteger)
    name = Column(String(255))
    email = Column(String(255))
    phone = Column(String(30))
    membership_no = Column(String(100), unique=True)
    valid_from = Column(Date)
    valid_until = Column(Date)
    max_books_allowed = Column(Integer)
    current_books_issued = Column(Integer)
    status = Column(Integer)
    notes = Column(Text)
    created_by_id = Column(Integer)
    created_at = Column(DateTime, server_default=func.now())
    updated_at = Column(DateTime, server_default=func.now(), onupdate=func.now())

class OrgLibraryLoan(Base):
    __tablename__ = 'org_library_loans'
    id = Column(BigInteger, primary_key=True)
    organization_id = Column(Integer)
    copy_id = Column(BigInteger, ForeignKey('org_library_book_copies.id'))
    member_id = Column(BigInteger, ForeignKey('org_library_members.id'), index=True)
    issued_by_id = Column(Integer)
    returned_by_id = Column(Integer)
    issue_date = Column(DateTime)
    due_date = Column(DateTime)
    return_date = Column(DateTime)
    renew_count = Column(Integer)
    status = Column(Integer)
    issue_notes = Column(Text)
    return_notes = Column(Text)
    created_at = Column(DateTime, server_default=func.now())
    updated_at = Column(DateTime, server_default=func.now(), onupdate=func.now())

class OrgLibraryReservation(Base):
    __tablename__ = 'org_library_reservations'
    id = Column(BigInteger, primary_key=True)
    organization_id = Column(Integer)
    book_id = Column(BigInteger, ForeignKey('org_library_books.id'))
    member_id = Column(BigInteger, ForeignKey('org_library_members.id'))
    queue_position = Column(Integer)
    reserved_at = Column(DateTime)
    expires_at = Column(DateTime)
    status = Column(Integer)
    fulfilled_copy_id = Column(BigInteger)
    created_at = Column(DateTime, server_default=func.now())
    updated_at = Column(DateTime, server_default=func.now(), onupdate=func.now())

class OrgLibraryFine(Base):
    __tablename__ = 'org_library_fines'
    id = Column(BigInteger, primary_key=True)
    organization_id = Column(Integer)
    member_id = Column(BigInteger, ForeignKey('org_library_members.id'))
    loan_id = Column(BigInteger, ForeignKey('org_library_loans.id'))
    amount = Column(Numeric(10, 2))
    reason = Column(String(255))
    status = Column(Integer)
    due_date = Column(Date)
    paid_at = Column(DateTime)
    waived_at = Column(DateTime)
    created_by_id = Column(Integer)
    created_at = Column(DateTime, server_default=func.now())
    updated_at = Column(DateTime, server_default=func.now(), onupdate=func.now())
